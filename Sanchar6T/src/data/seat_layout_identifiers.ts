// Type-safe helper function
export const getBerthLevel = (seatType?: string | null): BerthLevel => {
  if (!seatType) return "Unknown";

  const code = seatType.trim() as LayoutCode;
  const cleanCode = code.startsWith(".") ? code.slice(1) : code;

  return (cleanCode in BERTH_LEVEL_MAP)
    ? BERTH_LEVEL_MAP[cleanCode as keyof typeof BERTH_LEVEL_MAP]
    : "Unknown";
};
